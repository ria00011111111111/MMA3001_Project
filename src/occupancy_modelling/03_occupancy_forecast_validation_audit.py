
"""Audit the timing and integrity of the occupancy forecast.

The script reads the held-out forecast predictions generated by the
occupancy forecasting pipeline and performs a series of validation checks.

The audit examines:
    - Whether forecast target timestamps are five minutes after their origins.
    - The timing offset of current observations relative to forecast origins.
    - Duplicate floor-space and forecast-origin combinations.
    - Whether occupancy-state labels belong to the expected state set.
    - Whether persistence predictions match the current recorded state.
    - The number and temporal coverage of predictions for each floor space.

The script saves a floor-space coverage CSV and a text audit report to
``outputs/occupancy_forecast_v2``.

Paths are resolved relative to this file rather than the current working
directory.

Important interpretation notes:
    - The forecast target timestamp is not necessarily the timestamp of the
      actual future sensor observation.
    - The predictions file does not contain the actual future observation
      timestamp, so the elapsed time between current and future observations
      cannot be verified directly using this audit.
    - The audit checks recorded sensor states, not independently verified
      physical occupancy.
"""

from pathlib import Path
import sys
sys.dont_write_bytecode = True
import numpy as np
import pandas as pd


# ---------------------------------------------------------------------------
# 1. SETTINGS
# ---------------------------------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parents[2]

OUTPUT_DIR = PROJECT_ROOT / "outputs" / "occupancy_forecast_v2"
PREDICTIONS_FILE = OUTPUT_DIR / "test_forecast_predictions.csv"

FORECAST_MINUTES = 5
TOLERANCE_SECONDS = 60

REQUIRED_COLUMNS = [
    "forecast_origin",
    "forecast_target_time",
    "collecteddate",
    "floorspaceid",
    "current_state",
    "actual_future_state",
    "random_forest_prediction",
    "persistence_prediction",
]

TIMESTAMP_COLUMNS = [
    "forecast_origin",
    "forecast_target_time",
    "collecteddate",
]

STATE_COLUMNS = [
    "current_state",
    "actual_future_state",
    "random_forest_prediction",
    "persistence_prediction",
]

VALID_STATES = {
    "CurrentlyOccupied",
    "RecentlyOccupied",
    "NotOccupied",
}


# ---------------------------------------------------------------------------
# 2. INPUT VALIDATION AND LOADING
# ---------------------------------------------------------------------------

def load_predictions():
    """Load and validate the held-out forecast prediction data.

    Reads the prediction CSV generated by the forecasting pipeline, checks
    that all required columns are present, and converts the relevant timestamp
    columns to UTC datetime values.

    Rows containing missing values in required columns are removed before
    the audit proceeds.

    Returns:
        pd.DataFrame: Prediction data with parsed timestamps and complete
        required fields.

    Raises:
        FileNotFoundError: If the forecast prediction CSV does not exist.
        ValueError: If one or more required columns are missing.

    Note:
        Invalid timestamps are converted to NaT during parsing and are
        subsequently removed with other incomplete rows. A warning is printed
        if missing values are detected in the required columns.
    """
    if not PREDICTIONS_FILE.exists():
        raise FileNotFoundError(
            f"Forecast predictions not found: {PREDICTIONS_FILE}"
        )

    data = pd.read_csv(PREDICTIONS_FILE)

    missing = set(REQUIRED_COLUMNS) - set(data.columns)

    if missing:
        raise ValueError(f"Missing required columns: {sorted(missing)}")

    # Parse timestamps as UTC.
    for column in TIMESTAMP_COLUMNS:
        data[column] = pd.to_datetime(
            data[column], utc=True, errors="coerce"
        )

    if data[REQUIRED_COLUMNS].isna().any().any():
        print("WARNING: Required columns contain missing values.")

    data = data.dropna(subset=REQUIRED_COLUMNS).copy()

    return data


# ---------------------------------------------------------------------------
# 3. FORECAST HORIZON VALIDATION
# ---------------------------------------------------------------------------

def audit_forecast_horizon(data):
    """Verify that forecast targets are five minutes after their origins.

    Calculates the nominal forecast horizon by subtracting each forecast
    origin timestamp from its corresponding target timestamp.

    The resulting time differences are converted to minutes and compared
    against the expected forecast horizon defined by FORECAST_MINUTES.

    Args:
        data (pd.DataFrame): Validated forecast prediction data containing
            ``forecast_origin`` and ``forecast_target_time``.

    Returns:
        pd.DataFrame: Copy of the input data with an additional
        ``nominal_horizon_minutes`` column.

    Raises:
        AssertionError: If any nominal forecast horizon differs from the
            expected five-minute interval.

    Note:
        This check verifies the difference between the stored forecast
        origin and target timestamps. It does not verify the actual elapsed
        time between the underlying sensor observations.
    """
    data = data.copy()

    data["nominal_horizon_minutes"] = (
        data["forecast_origin"] - data["collecteddate"]
    ).dt.total_seconds() / 60

    print("\n1. NOMINAL FORECAST HORIZON")
    print(data["nominal_horizon_minutes"].describe().to_string())

    assert np.allclose(
        data["nominal_horizon_minutes"], FORECAST_MINUTES
    ), "Some forecast target timestamps are not five minutes after origin."

    print("PASS: All nominal target timestamps are five minutes ahead.")

    return data


# ---------------------------------------------------------------------------
# 4. CURRENT OBSERVATION TIMING
# ---------------------------------------------------------------------------

def audit_current_observation_timing(data):
    """Calculate the current observation timestamp offset from its origin.

    Compares ``collecteddate``, the timestamp of the current sensor
    observation, with ``forecast_origin``. The difference is converted
    into seconds to show how far the original observation timestamp is
    from the forecast origin.

    Args:
        data (pd.DataFrame): Validated forecast prediction data containing
            ``collecteddate`` and ``forecast_origin``.

    Returns:
        pd.DataFrame: Copy of the input data with an additional
        ``current_observation_offset_seconds`` column.

    Note:
        The actual timestamp of the future sensor observation is not stored
        in the prediction file. Consequently, this calculation cannot
        establish the elapsed time between the current and future sensor
        observations.

        TOLERANCE_SECONDS is defined as an audit setting but is not applied
        as a pass/fail threshold in the current implementation.
    """
    data = data.copy()

    data["current_observation_offset_seconds"] = (
        data["collecteddate"] - data["forecast_origin"]
    ).dt.total_seconds()

    print("\n2. CURRENT OBSERVATION TIMING WITHIN ITS BIN")
    print(data["current_observation_offset_seconds"].describe().to_string())

    return data


# ---------------------------------------------------------------------------
# 5. DUPLICATE FORECAST ORIGIN CHECK
# ---------------------------------------------------------------------------

def audit_duplicate_origins(data):
    """Check for duplicate floor-space and forecast-origin combinations.

    Identifies repeated combinations of ``floorspaceid`` and
    ``forecast_origin``. Each duplicate occurrence after the first is
    counted.

    Args:
        data (pd.DataFrame): Validated forecast prediction data.

    Returns:
        int: Number of duplicate floor-space and forecast-origin pairs.

    Note:
        This check identifies duplicate forecast origins within individual
        floor spaces. It does not check whether different floor spaces share
        the same forecast origin, as those are valid separate observations.
    """
    duplicates = data.duplicated(
        subset=["floorspaceid", "forecast_origin"]
    ).sum()

    print("\n3. DUPLICATE FORECAST ORIGINS")
    print(f"Duplicate floor-space/origin pairs: {duplicates:,}")

    if duplicates:
        print("WARNING: Duplicate forecast origins were found.")
    else:
        print("PASS: No duplicate floor-space/origin pairs.")

    return duplicates


# ---------------------------------------------------------------------------
# 6. OCCUPANCY-STATE LABEL VALIDATION
# ---------------------------------------------------------------------------

def audit_state_labels(data):
    """Check that recorded and predicted states use the expected labels.

    Examines the current state, actual future state, Random Forest prediction,
    and persistence prediction columns. Any values outside the predefined
    VALID_STATES set are reported.

    Args:
        data (pd.DataFrame): Validated forecast prediction data containing
            all required state columns.

    Returns:
        dict[str, set]: Dictionary mapping each checked column to the set
        of unexpected labels found. Columns without unexpected labels are
        associated with an empty set.

    Note:
        Unexpected labels generate warnings but do not stop the audit.
        This allows the remaining validation checks to continue.
    """
    unexpected_labels = {}

    for column in STATE_COLUMNS:
        unexpected = set(data[column].unique()) - VALID_STATES
        unexpected_labels[column] = unexpected

        if unexpected:
            print(f"WARNING: Unexpected values in {column}: {unexpected}")

    return unexpected_labels


# ---------------------------------------------------------------------------
# 7. PERSISTENCE BASELINE VALIDATION
# ---------------------------------------------------------------------------

def audit_persistence_predictions(data):
    """Verify that persistence predictions equal the current recorded state.

    The persistence baseline assumes that the future occupancy state will
    remain equal to the current recorded occupancy state.

    Compares ``persistence_prediction`` against ``current_state`` for every
    prediction row and counts the number of mismatches.

    Args:
        data (pd.DataFrame): Validated forecast prediction data containing
            ``persistence_prediction`` and ``current_state``.

    Returns:
        int: Number of persistence predictions that differ from the
        corresponding current state.

    Raises:
        AssertionError: If any persistence prediction differs from the
            current recorded state.

    Note:
        This verifies the implementation of the persistence baseline. It
        does not establish whether the persistence baseline is an accurate
        predictor of future occupancy.
    """
    persistence_mismatches = (
        data["persistence_prediction"] != data["current_state"]
    ).sum()

    print("\n4. PERSISTENCE BASELINE CHECK")
    print(f"Mismatches: {persistence_mismatches:,}")

    assert persistence_mismatches == 0, (
        "Persistence predictions do not always equal current state."
    )

    print("PASS: Persistence predicts the current state.")

    return persistence_mismatches


# ---------------------------------------------------------------------------
# 8. TEST COVERAGE BY FLOOR SPACE
# ---------------------------------------------------------------------------

def calculate_test_coverage(data):
    """Summarise the number and temporal coverage of predictions per floor space.

    Groups the held-out prediction data by floor-space identifier and
    calculates:
        - The number of prediction rows.
        - The earliest forecast target timestamp.
        - The latest forecast target timestamp.

    Args:
        data (pd.DataFrame): Validated forecast prediction data containing
            ``floorspaceid`` and ``forecast_target_time``.

    Returns:
        pd.DataFrame: Coverage summary containing one row per floor space,
        with prediction counts and first and last target timestamps.

    Outputs:
        Writes ``forecast_validation_coverage.csv`` to OUTPUT_DIR.

    Note:
        The first and last target timestamps describe the temporal extent of
        the recorded test predictions. They do not establish that every
        five-minute interval within that period contains a prediction.
    """
    coverage = (
        data.groupby("floorspaceid")
        .agg(
            predictions=("actual_future_state", "size"),
            first_target=("forecast_target_time", "min"),
            last_target=("forecast_target_time", "max"),
        )
        .reset_index()
    )

    coverage.to_csv(
        OUTPUT_DIR / "forecast_validation_coverage.csv",
        index=False,
    )

    return coverage


# ---------------------------------------------------------------------------
# 9. AUDIT REPORT
# ---------------------------------------------------------------------------

def write_audit_report(data, duplicates, persistence_mismatches):
    """Write a text report summarising the forecast validation audit.

    Records the number of prediction rows checked, expected nominal forecast
    horizon, duplicate forecast-origin count, and persistence baseline
    mismatches.

    The report also documents the limitation that the actual future sensor
    observation timestamp is not included in the prediction CSV.

    Args:
        data (pd.DataFrame): Validated prediction data used in the audit.
        duplicates (int): Number of duplicate floor-space and forecast-origin
            pairs identified.
        persistence_mismatches (int): Number of persistence baseline
            predictions that differ from the current recorded state.

    Returns:
        None.

    Outputs:
        Writes ``forecast_validation_audit.txt`` to OUTPUT_DIR.
    """
    report = [
        "OCCUPANCY FORECAST VALIDATION AUDIT",
        f"Rows checked: {len(data):,}",
        f"Nominal horizon minutes: {FORECAST_MINUTES}",
        f"Duplicate origins: {duplicates:,}",
        f"Persistence mismatches: {persistence_mismatches:,}",
        "",
        "IMPORTANT LIMITATION:",
        "The predictions file does not contain the actual timestamp",
        "of the future observation used to create each target.",
        "Therefore, actual elapsed time between the current and future",
        "sensor observations cannot be verified using this file alone.",
        "The source data must be reprocessed to audit that interval.",
    ]

    (OUTPUT_DIR / "forecast_validation_audit.txt").write_text(
        "\n".join(report),
        encoding="utf-8",
    )


# ---------------------------------------------------------------------------
# 10. MAIN WORKFLOW
# ---------------------------------------------------------------------------

def main():
    """Execute the occupancy forecast validation audit.

    Loads and validates the held-out prediction data, then performs the
    forecast horizon, current observation timing, duplicate origin, state
    label, and persistence baseline checks.

    Calculates test coverage for each floor space and writes the audit
    report to the forecasting output directory.

    Returns:
        None.

    Raises:
        FileNotFoundError: If the forecast prediction CSV is unavailable.
        ValueError: If required columns are missing from the prediction file.
        AssertionError: If the nominal forecast horizon or persistence
            baseline validation fails.

    Note:
        Unexpected state labels and duplicate forecast origins generate
        warnings but do not stop execution. Failed assertions stop the
        workflow before the remaining outputs are generated.
    """
    print("=" * 65)
    print("OCCUPANCY FORECAST VALIDATION AUDIT")
    print("=" * 65)

    data = load_predictions()

    data = audit_forecast_horizon(data)
    data = audit_current_observation_timing(data)

    duplicates = audit_duplicate_origins(data)

    audit_state_labels(data)

    persistence_mismatches = audit_persistence_predictions(data)

    calculate_test_coverage(data)

    write_audit_report(
        data,
        duplicates,
        persistence_mismatches,
    )

    print("\nSaved validation audit to:")
    print(OUTPUT_DIR)
    print("\nAudit complete.")


if __name__ == "__main__":
    main()
