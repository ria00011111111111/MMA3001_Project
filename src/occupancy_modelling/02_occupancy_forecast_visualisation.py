def plot_confusion_matrices(actual, predicted, labels):
    """Save raw-count and row-normalised confusion matrices.

    The raw matrix shows the number of predictions for each actual and
    predicted class combination. The normalised matrix expresses each row
    as a proportion of its actual class, making class-level performance
    easier to compare despite class imbalance.

    Args:
        actual: Ground-truth occupancy states.
        predicted: Random Forest predictions.
        labels (list): Ordered occupancy-state labels.
    """

    # Calculate the confusion matrix using the specified class ordering.
    matrix = confusion_matrix(
        actual,
        predicted,
        labels=labels,
    )

    # -------------------------------------------------------
    # Raw-count confusion matrix
    # -------------------------------------------------------

    fig, ax = plt.subplots(
        figsize=(9, 7)
    )

    image = ax.imshow(
        matrix,
        interpolation="nearest",
    )

    fig.colorbar(
        image,
        ax=ax,
        label="Number of predictions",
    )

    ax.set(
        xticks=np.arange(len(labels)),
        yticks=np.arange(len(labels)),
        xticklabels=labels,
        yticklabels=labels,
        xlabel="Predicted future state",
        ylabel="Actual future state",
        title="Random Forest Confusion Matrix",
    )

    plt.setp(
        ax.get_xticklabels(),
        rotation=25,
        ha="right",
    )

    # Annotate each cell with its corresponding prediction count.
    threshold = (
        matrix.max() / 2
        if matrix.size
        else 0
    )

    for row in range(matrix.shape[0]):
        for column in range(matrix.shape[1]):

            value = matrix[row, column]

            ax.text(
                column,
                row,
                f"{value:,}",
                ha="center",
                va="center",
                color=(
                    "white"
                    if value > threshold
                    else "black"
                ),
            )

    fig.tight_layout()

    fig.savefig(
        OUTPUT_DIR / FIGURE_FILENAMES[0],
        dpi=200,
        bbox_inches="tight",
    )

    plt.close(fig)

    # -------------------------------------------------------
    # Row-normalised confusion matrix
    # -------------------------------------------------------

    # Divide each row by its actual class total to show the proportion
    # of predictions assigned to each predicted class.
    row_totals = matrix.sum(
        axis=1,
        keepdims=True,
    )

    # Avoid division by zero if an actual class has no test observations.
    normalised = np.divide(
        matrix,
        row_totals,
        out=np.zeros_like(
            matrix,
            dtype=float,
        ),
        where=row_totals != 0,
    )

    fig, ax = plt.subplots(
        figsize=(9, 7)
    )

    image = ax.imshow(
        normalised,
        vmin=0,
        vmax=1,
        interpolation="nearest",
    )

    fig.colorbar(
        image,
        ax=ax,
        label="Proportion of actual class",
    )

    ax.set(
        xticks=np.arange(len(labels)),
        yticks=np.arange(len(labels)),
        xticklabels=labels,
        yticklabels=labels,
        xlabel="Predicted future state",
        ylabel="Actual future state",
        title="Normalised Random Forest Confusion Matrix",
    )

    plt.setp(
        ax.get_xticklabels(),
        rotation=25,
        ha="right",
    )

    # Display each normalised value as a percentage.
    for row in range(normalised.shape[0]):
        for column in range(normalised.shape[1]):

            value = normalised[row, column]

            ax.text(
                column,
                row,
                f"{value:.1%}",
                ha="center",
                va="center",
                color=(
                    "white"
                    if value > 0.5
                    else "black"
                ),
            )

    fig.tight_layout()

    fig.savefig(
        OUTPUT_DIR / FIGURE_FILENAMES[1],
        dpi=200,
        bbox_inches="tight",
    )

    plt.close(fig)


