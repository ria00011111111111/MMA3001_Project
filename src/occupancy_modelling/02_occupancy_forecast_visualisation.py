def plot_representative_time_series(predictions):
    """Plot actual and predicted states over a representative 48-hour period.

    Selects the floor-space with the largest number of held-out predictions,
    identifies a 48-hour window around its midpoint and plots the actual
    future state alongside Random Forest and persistence predictions.

    Args:
        predictions (pd.DataFrame): Held-out forecast predictions.

    Returns:
        tuple: Selected floor-space ID and number of plotted observations.
    """

    print("\nCreating time-series comparison...")

    # Select the floor-space with the greatest number of held-out predictions.
    floor_counts = predictions["floorspaceid"].value_counts()

    if floor_counts.empty:
        print(
            "Skipping time-series plot: no floor-space IDs are available."
        )
        return None, 0

    selected_floor = floor_counts.index[0]

    floor_data = predictions.loc[
        predictions["floorspaceid"] == selected_floor
    ].copy()

    # Sort by target timestamp and remove any duplicate target times.
    floor_data = floor_data.sort_values(
        "forecast_target_time"
    )

    floor_data = floor_data.drop_duplicates(
        subset=[
            "forecast_target_time",
        ],
        keep="last",
    )

    if floor_data.empty:
        print(
            "Skipping time-series plot: no usable rows."
        )
        return selected_floor, 0

    # Centre the visualisation on the middle of the available forecast period.
    centre_time = floor_data.iloc[
        len(floor_data) // 2
    ]["forecast_target_time"]

    # Select a 48-hour window extending 24 hours either side of the midpoint.
    window_start = (
        centre_time - pd.Timedelta(hours=24)
    )

    window_end = (
        centre_time + pd.Timedelta(hours=24)
    )

    plot_data = floor_data.loc[
        floor_data["forecast_target_time"].between(
            window_start,
            window_end,
        )
    ].copy()

    # Convert categorical occupancy states into numerical positions
    # so that they can be displayed using a step plot.
    state_codes = {
        state: index
        for index, state in enumerate(STATE_ORDER)
    }

    for column, output_column in (
        ("actual_future_state", "actual_code"),
        ("random_forest_prediction", "predicted_code"),
        ("persistence_prediction", "persistence_code"),
    ):
        plot_data[output_column] = (
            plot_data[column].map(state_codes)
        )

    # Unexpected occupancy labels are left as NaN and appear as gaps.
    if plot_data[
        [
            "actual_code",
            "predicted_code",
            "persistence_code",
        ]
    ].isna().any().any():

        print(
            "Warning: unexpected state labels will appear as gaps."
        )

    fig, ax = plt.subplots(
        figsize=(15, 6)
    )

    # Plot the recorded future occupancy state and both model predictions.
    ax.step(
        plot_data["forecast_target_time"],
        plot_data["actual_code"],
        where="post",
        label="Actual future state",
    )

    ax.step(
        plot_data["forecast_target_time"],
        plot_data["predicted_code"],
        where="post",
        label="Random Forest prediction",
        alpha=0.85,
    )

    ax.step(
        plot_data["forecast_target_time"],
        plot_data["persistence_code"],
        where="post",
        label="Persistence prediction",
        alpha=0.7,
    )

    ax.set_yticks(
        range(len(STATE_ORDER)),
        STATE_ORDER,
    )

    ax.set_title(
        "Actual vs Predicted Occupancy States "
        "(Representative 48-Hour Window)"
    )

    ax.set_xlabel(
        "Forecast target time (UTC)"
    )

    ax.set_ylabel(
        "Recorded occupancy state"
    )

    ax.legend()

    ax.grid(
        True,
        axis="y",
        alpha=0.3,
    )

    fig.autofmt_xdate()
    fig.tight_layout()

    fig.savefig(
        OUTPUT_DIR / FIGURE_FILENAMES[5],
        dpi=200,
        bbox_inches="tight",
    )

    plt.close(fig)

    # Export the observations used in the representative time-series plot.
    plot_data.to_csv(
        OUTPUT_DIR / "representative_time_series.csv",
        index=False,
    )

    print(
        f"Selected floor space: {selected_floor}"
    )

    print(
        f"Time-series points plotted: {len(plot_data):,}"
    )

    return (
        selected_floor,
        len(plot_data),
    )


