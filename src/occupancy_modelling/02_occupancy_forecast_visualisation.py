def plot_feature_importance(importance):
    """Plot the 15 most important Random Forest input features.

    Feature importance values are cleaned and sorted before plotting.
    The function skips the plot if no valid importance values are available.

    Args:
        importance (pd.DataFrame): Feature names and importance values.

    Returns:
        bool: True if the plot was generated, otherwise False.
    """

    if importance.empty:
        print(
            "Skipping feature-importance plot: no rows are available."
        )
        return False

    importance = importance.copy()

    # Convert importance values to numeric form and remove invalid entries.
    importance["importance"] = pd.to_numeric(
        importance["importance"],
        errors="coerce",
    )

    importance = importance.dropna(
        subset=[
            "feature",
            "importance",
        ]
    )

