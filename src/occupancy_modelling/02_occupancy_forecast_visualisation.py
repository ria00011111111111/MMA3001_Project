def calculate_class_f1(actual, predicted, state):
    """Calculate the one-vs-rest F1 score for an occupancy state.

    Treats the selected state as the positive class and all other states
    as the negative class.

    Args:
        actual: Ground-truth occupancy states.
        predicted: Predicted occupancy states.
        state (str): Occupancy state being evaluated.

    Returns:
        float: F1 score for the selected occupancy state.
    """

    actual = np.asarray(actual)
    predicted = np.asarray(predicted)

    # Calculate true positives, false positives and false negatives
    # for the selected occupancy state.
    tp = np.sum(
        (actual == state) & (predicted == state)
    )

    fp = np.sum(
        (actual != state) & (predicted == state)
    )

    fn = np.sum(
        (actual == state) & (predicted != state)
    )

    denominator = (
        2 * tp + fp + fn
    )

    # Return zero if the class has no positive predictions or observations.
    return (
        2 * tp / denominator
        if denominator
        else 0.0
    )


def plot_class_level_f1(actual, rf_pred, persistence_pred, labels):
    """Export and plot per-class F1 scores for Random Forest and persistence.

    Calculates one-vs-rest F1 scores for each occupancy state, exports
    the results to CSV and generates a grouped bar chart.

    Args:
        actual: Ground-truth occupancy states.
        rf_pred: Random Forest predictions.
        persistence_pred: Persistence baseline predictions.
        labels (list): Occupancy-state labels to evaluate.
    """

    results = []

    # Calculate the F1 score for each occupancy state and model.
