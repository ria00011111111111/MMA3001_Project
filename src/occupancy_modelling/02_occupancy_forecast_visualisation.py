"""Train, evaluate and visualise next-interval occupancy forecasts.

The script:
1. Loads occupancy observations from a compressed CSV dataset.
2. Aggregates observations into five-minute intervals, retaining the
   latest observation for each floor-space and interval.
3. Constructs forecasting samples using consecutive five-minute intervals.
4. Trains and evaluates a Random Forest using a chronological train/test split.
5. Compares the model against majority-class and persistence baselines.
6. Exports predictions, model metrics and feature importance.
7. Generates diagnostic visualisations and a text summary.

All timestamps are interpreted and stored in UTC. The prediction target is
the recorded sensor occupancy state at the next interval; it is not an
independently verified measurement of physical occupancy.
"""

