def require_columns(dataframe, required_columns, file_path):
    """Check that a DataFrame contains all required columns.

    Args:
        dataframe (pd.DataFrame): DataFrame to validate.
        required_columns (list): Column names required by the analysis.
        file_path (Path): Source file used in the error message.

    Raises:
        ValueError: If one or more required columns are missing.
    """
    missing = sorted(
        set(required_columns) - set(dataframe.columns)
    )

    if missing:
        raise ValueError(
            f"{file_path} is missing required column(s): "
            f"{', '.join(missing)}"
        )


def load_inputs():
    """Load and validate the forecast CSV files generated by the model.

    Reads the prediction, model comparison and feature importance files.
    Forecast timestamps are converted to UTC and invalid prediction rows
    are removed before visualisation.

    Returns:
        tuple: Predictions, model comparison and feature importance
            DataFrames.

    Raises:
        FileNotFoundError: If a required CSV file is unavailable.
        ValueError: If required columns or valid prediction rows are missing.
    """

    # Check that all model outputs exist before attempting to load them.
    for path in (
        PREDICTIONS_FILE,
        COMPARISON_FILE,
        IMPORTANCE_FILE,
    ):
        if not path.is_file():
            raise FileNotFoundError(
                f"Required forecast output was not found: {path}"
            )

    predictions = pd.read_csv(
        PREDICTIONS_FILE
    )

    comparison = pd.read_csv(
        COMPARISON_FILE
    )

    importance = pd.read_csv(
        IMPORTANCE_FILE
    )

    # Validate the structure of each CSV before using its contents.
    require_columns(
        predictions,
        PREDICTION_COLUMNS,
        PREDICTIONS_FILE,
    )

    require_columns(
        comparison,
        ["model", *METRIC_COLUMNS],
        COMPARISON_FILE,
    )

    require_columns(
        importance,
        ["feature", "importance"],
        IMPORTANCE_FILE,
    )

    # Convert forecast timestamps back to timezone-aware UTC values.
    for column in (
        "forecast_origin",
        "forecast_target_time",
    ):
        predictions[column] = pd.to_datetime(
            predictions[column],
            utc=True,
            errors="coerce",
        )

    # Remove rows containing missing values in required prediction fields.
    predictions = predictions.dropna(
        subset=PREDICTION_COLUMNS
    ).copy()

    if predictions.empty:
        raise ValueError(
            "No valid forecast prediction rows remain."
        )

    # Ensure that occupancy labels have consistent string representations.
    for column in (
        "actual_future_state",
        "random_forest_prediction",
        "persistence_prediction",
    ):
        predictions[column] = (
            predictions[column].astype(str)
        )

    if comparison.empty:
        raise ValueError(
            f"Model comparison file is empty: {COMPARISON_FILE}"
        )

    return (
        predictions,
        comparison,
        importance,
    )


def get_state_labels(actual, *predicted_series):
    """Determine the occupancy-state labels represented in the forecasts.

    Uses the preferred occupancy-state ordering and appends any additional
    labels found in the actual or predicted values.

    Args:
        actual: Actual future occupancy states.
        *predicted_series: One or more prediction series.

    Returns:
        list: Occupancy-state labels in a consistent plotting order.
    """
    observed = set(
        actual.dropna().astype(str)
    )

    # Include labels found in every prediction series.
    for series in predicted_series:
        observed.update(
            series.dropna().astype(str)
        )

    # Preserve the preferred order while allowing unexpected labels
    # to remain visible in evaluation outputs.
    return [
        state
        for state in STATE_ORDER
        if state in observed
    ] + sorted(
        observed - set(STATE_ORDER)
    )


