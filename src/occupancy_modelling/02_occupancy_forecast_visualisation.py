def evaluate_model(name, actual, predicted, labels):
    """Calculate classification metrics for a forecasting model.

    Computes accuracy, balanced accuracy, macro F1 and weighted F1.
    Explicit class labels ensure that the F1 calculations use a consistent
    set of occupancy classes across the evaluated models.

    Args:
        name (str): Model or baseline name.
        actual: Ground-truth occupancy states.
        predicted: Predicted occupancy states.
        labels (list): Occupancy classes included in the evaluation.

    Returns:
        dict: Model name and calculated evaluation metrics.
    """
    return {
        "model": name,

        "accuracy": accuracy_score(
            actual,
            predicted,
        ),

        "balanced_accuracy": balanced_accuracy_score(
            actual,
            predicted,
        ),

        "macro_f1": f1_score(
            actual,
            predicted,
            labels=labels,
            average="macro",
            zero_division=0,
        ),

        "weighted_f1": f1_score(
            actual,
            predicted,
            labels=labels,
            average="weighted",
            zero_division=0,
        ),
    }


def generate_forecast_outputs(data):
    """Train and evaluate the Random Forest forecasting model.

    Creates a chronological training and testing split using forecast
    origin times. Training targets are restricted to timestamps before
    the test period to prevent temporal overlap. The Random Forest is
    compared against majority-class and persistence baselines.

    The function exports:
        - Held-out forecast predictions.
        - Model comparison metrics.
        - Random Forest feature importance.

    Args:
        data (pd.DataFrame): Supervised forecasting dataset.

    Returns:
        tuple: Prediction output, model comparison DataFrame and feature
            importance DataFrame.

    Raises:
        ValueError: If the dataset cannot produce valid training and test sets.
        AssertionError: If temporal overlap is detected at the split boundary.
    """

    # Separate categorical identifiers and states from numerical
    # calendar-based predictors.
    categorical_features = [
        "floorspaceid",
        "current_state",
    ]

    numeric_features = [
        "hour",
        "day_of_week",
        "month",
        "is_weekend",
    ]

    feature_columns = (
        categorical_features + numeric_features
    )

    X = data[feature_columns].copy()
    y = data["actual_future_state"].copy()

    # Use unique forecast-origin timestamps to establish a chronological
    # split rather than randomly splitting individual observations.
    unique_times = np.sort(
        data["interval"].unique()
    )

    if len(unique_times) < 2:
        raise ValueError(
            "Not enough distinct forecast-origin times to split."
        )

    split_index = int(
        len(unique_times) * (1 - TEST_FRACTION)
    )

    # Ensure that both training and testing periods contain timestamps.
    split_index = min(
        max(split_index, 1),
        len(unique_times) - 1,
    )

    cutoff_time = unique_times[split_index]

    # Training targets must also finish before the test forecast-origin
    # period. This prevents temporal overlap across the split boundary.
    train_mask = (
        (data["interval"] < cutoff_time)
        & (data["forecast_target_time"] < cutoff_time)
    )

    test_mask = (
        data["interval"] >= cutoff_time
    )

    X_train = X.loc[train_mask]
    X_test = X.loc[test_mask]

    y_train = y.loc[train_mask]
    y_test = y.loc[test_mask]

    if X_train.empty or X_test.empty:
        raise ValueError(
            "Chronological split produced an empty train or test set."
        )

    if y_train.nunique() < 2:
        raise ValueError(
            "Training data contains fewer than two target classes."
        )

    # Independently check that the final training target occurs before
    # the first testing forecast origin.
    train_target_end = (
        data.loc[train_mask, "forecast_target_time"].max()
    )

    test_origin_start = (
        data.loc[test_mask, "interval"].min()
    )

    if train_target_end >= test_origin_start:
        raise AssertionError(
            "Temporal leakage detected across the train/test boundary."
        )

    print("\nChronological split")
    print(f"Training forecast pairs: {len(X_train):,}")
    print(f"Testing forecast pairs: {len(X_test):,}")
    print(f"Training target period ends: {train_target_end}")
    print(f"Testing forecast origins begin: {test_origin_start}")

    # Majority-class baseline: always predict the most frequent
    # future occupancy state in the training dataset.
    majority_state = y_train.value_counts().idxmax()

    majority_predictions = np.full(
        len(y_test),
        majority_state,
        dtype=object,
    )

    # Persistence baseline: assume the next occupancy state remains
    # unchanged from the current recorded state.
    persistence_predictions = (
        data.loc[test_mask, "current_state"].to_numpy()
    )

    # One-hot encode categorical predictors and pass numerical
    # calendar features through without additional transformation.
    preprocessor = ColumnTransformer(
        transformers=[
            (
                "categorical",
                OneHotEncoder(handle_unknown="ignore"),
                categorical_features,
            ),
            (
                "numeric",
                "passthrough",
                numeric_features,
            ),
        ]
    )

    # Use a pipeline so preprocessing is fitted using training data only.
    # This ensures that test observations do not influence preprocessing.
    model = Pipeline(
        steps=[
            (
                "preprocessor",
                preprocessor,
            ),
            (
                "classifier",
                RandomForestClassifier(
                    n_estimators=100,
                    max_depth=12,
                    min_samples_leaf=10,
                    class_weight="balanced_subsample",
                    random_state=RANDOM_STATE,
                    n_jobs=-1,
                ),
            ),
        ]
    )

    print("\nTraining Random Forest...")

    model.fit(
        X_train,
        y_train,
    )

    # Generate predictions for the chronologically held-out test period.
    rf_predictions = model.predict(X_test)

    # Use a consistent set of class labels when calculating metrics.
    labels = sorted(
        set(y_train.unique()) | set(y_test.unique())
    )

    # Compare the Random Forest against both baseline approaches.
    comparison = pd.DataFrame([
        evaluate_model(
            "Majority-class baseline",
            y_test,
            majority_predictions,
            labels,
        ),
        evaluate_model(
            "Persistence",
            y_test,
            persistence_predictions,
            labels,
        ),
        evaluate_model(
            "Random Forest",
            y_test,
            rf_predictions,
            labels,
        ),
    ])

    comparison.to_csv(
        COMPARISON_FILE,
        index=False,
    )

    # Retrieve the transformed feature names and their corresponding
    # Random Forest impurity-based importance values.
    feature_names = (
        model.named_steps["preprocessor"].get_feature_names_out()
    )

    importances = (
        model.named_steps["classifier"].feature_importances_
    )

    importance = pd.DataFrame({
        "feature": feature_names,
        "importance": importances,
    }).sort_values(
        "importance",
        ascending=False,
    )

    importance.to_csv(
        IMPORTANCE_FILE,
        index=False,
    )

    # Assemble the held-out predictions with their forecast origins,
    # target timestamps and actual future states.
    prediction_output = data.loc[
        test_mask,
        [
            "interval",
            "forecast_target_time",
            "actual_future_state",
            "floorspaceid",
        ],
    ].copy()

    prediction_output = prediction_output.rename(
        columns={
            "interval": "forecast_origin",
        }
    )

    prediction_output["random_forest_prediction"] = (
        rf_predictions
    )

    prediction_output["persistence_prediction"] = (
        persistence_predictions
    )

    prediction_output = prediction_output[
        PREDICTION_COLUMNS
    ]

    prediction_output.to_csv(
        PREDICTIONS_FILE,
        index=False,
    )

    print("\nFORECAST MODEL COMPARISON")
    print(
        comparison.to_string(
            index=False,
            float_format="%.4f",
        )
    )

    print("\nForecast CSV files saved:")
    print(PREDICTIONS_FILE)
    print(COMPARISON_FILE)
    print(IMPORTANCE_FILE)

    return (
        prediction_output,
        comparison,
        importance,
    )


