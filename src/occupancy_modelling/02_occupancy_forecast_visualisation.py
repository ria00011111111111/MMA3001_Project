def load_and_aggregate_data():
    """Load and aggregate occupancy observations from the ZIP dataset.

    Reads the CSV in chunks to limit memory usage. Invalid timestamps and
    records missing required fields are removed. Observations are assigned
    to five-minute intervals, and the latest observation is retained for
    each floor-space and interval combination.

    Returns:
        pd.DataFrame: Aggregated observations containing floor-space ID,
            recorded occupancy state, original timestamp and interval.

    Raises:
        FileNotFoundError: If the ZIP file or an internal CSV is unavailable.
        ValueError: If no valid occupancy records are loaded.
    """
    if not ZIP_FILE.is_file():
        raise FileNotFoundError(
            f"Occupancy ZIP file was not found: {ZIP_FILE}"
        )

    print("\nLoading occupancy data from ZIP...")

    chunks = []
    total_rows = 0

    with ZipFile(ZIP_FILE) as archive:

        # Identify CSV files contained within the compressed dataset.
        csv_files = [
            name
            for name in archive.namelist()
            if name.lower().endswith(".csv")
        ]

        if not csv_files:
            raise FileNotFoundError(
                "No CSV file was found inside the occupancy ZIP."
            )

        with archive.open(csv_files[0]) as file:

            # Process the dataset in chunks to avoid loading all raw
            # observations into memory simultaneously.
            for chunk in pd.read_csv(
                file,
                usecols=[
                    "floorspaceid",
                    TARGET,
                    "collecteddate",
                ],
                chunksize=CHUNK_SIZE,
                low_memory=False,
            ):
                total_rows += len(chunk)

                # Convert timestamps to UTC. Invalid timestamps are
                # converted to NaT and removed during cleaning.
                chunk["collecteddate"] = pd.to_datetime(
                    chunk["collecteddate"],
                    utc=True,
                    errors="coerce",
                )

                # Remove records missing information required for forecasting.
                chunk = chunk.dropna(
                    subset=[
                        "floorspaceid",
                        TARGET,
                        "collecteddate",
                    ]
                )

                # Assign each observation to its corresponding
                # five-minute interval.
                chunk["interval"] = (
                    chunk["collecteddate"].dt.floor("5min")
                )

                chunks.append(
                    chunk[
                        [
                            "floorspaceid",
                            TARGET,
                            "collecteddate",
                            "interval",
                        ]
                    ]
                )

                print(
                    f"Processed {total_rows:,} raw records..."
                )

    if not chunks:
        raise ValueError(
            "No valid occupancy records were loaded."
        )

    print("\nCombining and aggregating records...")

    data = pd.concat(chunks, ignore_index=True)
    del chunks

    # Sort observations chronologically within each floor-space and
    # interval so that the latest recorded observation can be retained.
    data = data.sort_values(
        [
            "floorspaceid",
            "interval",
            "collecteddate",
        ]
    )

    # Retain only the latest observation for each floor-space and
    # five-minute interval combination.
    data = data.drop_duplicates(
        subset=[
            "floorspaceid",
            "interval",
        ],
        keep="last",
    )

    # Restore chronological ordering for subsequent forecasting operations.
    data = data.sort_values(
        [
            "floorspaceid",
            "interval",
        ]
    ).reset_index(drop=True)

    print(f"Raw records read: {total_rows:,}")
    print(f"Valid aggregated intervals: {len(data):,}")
    print(f"Floor spaces: {data['floorspaceid'].nunique()}")
    print(
        f"Interval range: {data['interval'].min()} "
        f"to {data['interval'].max()}"
    )

    return data


def build_forecast_dataset(data):
    """Construct supervised samples for next-interval forecasting.

    Each observation is paired with the following observation from the
    same floor-space. Only pairs exactly five minutes apart are retained.
    The current occupancy state and calendar variables are used as
    predictors, while the next interval's recorded state is the target.

    Args:
        data (pd.DataFrame): Aggregated occupancy observations.

    Returns:
        pd.DataFrame: Forecasting dataset containing predictor variables,
            forecast origins, target timestamps and future occupancy states.

    Raises:
        ValueError: If no consecutive five-minute pairs are available.
    """
    print("\nConstructing next-interval forecasting targets...")

    data = data.copy()

    # Group by floor-space so that future observations are never
    # accidentally taken from a different floor-space.
    grouped = data.groupby(
        "floorspaceid",
        sort=False,
    )

    # Shift each floor-space group independently to obtain its next
    # observation and corresponding timestamp.
    data["forecast_target_time"] = (
        grouped["interval"].shift(-1)
    )

    data["actual_future_state"] = (
        grouped[TARGET].shift(-1)
    )

    # Retain only pairs where the next observation occurs exactly
    # five minutes after the current forecast origin.
    expected_target = (
        data["interval"] + pd.Timedelta(minutes=5)
    )

    data = data.loc[
        data["forecast_target_time"] == expected_target
    ].copy()

    if data.empty:
        raise ValueError(
            "No consecutive five-minute interval pairs were found."
        )

    # Define the current occupancy state and the future target as strings.
    data["current_state"] = data[TARGET].astype(str)
    data["actual_future_state"] = (
        data["actual_future_state"].astype(str)
    )

    # Extract calendar-based predictors from the forecast-origin timestamp.
    data["hour"] = data["interval"].dt.hour
    data["day_of_week"] = data["interval"].dt.dayofweek
    data["month"] = data["interval"].dt.month

    # Monday-Friday = 0; Saturday-Sunday = 1.
    data["is_weekend"] = (
        data["day_of_week"] >= 5
    ).astype(int)

    print(
        f"Consecutive forecast pairs: {len(data):,}"
    )

    return data


