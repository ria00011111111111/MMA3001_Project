
"""Compare per-class occupancy forecasting performance across rolling windows.

Reads predictions generated by the rolling occupancy evaluation and calculates
precision, recall, F1-score, and support for each occupancy class and model.

Outputs:
    outputs/occupancy_rolling_evaluation/rolling_class_level_metrics.csv

The script only analyses saved predictions. It does not train models or modify
the original prediction file.
"""

from pathlib import Path

import pandas as pd
from sklearn.metrics import classification_report


# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parents[2]

OUTPUT_DIR = PROJECT_ROOT / "outputs" / "occupancy_rolling_evaluation"
INPUT_FILE = OUTPUT_DIR / "rolling_evaluation_predictions.csv"
OUTPUT_FILE = OUTPUT_DIR / "rolling_class_level_metrics.csv"

# Keep this order consistent across evaluation scripts.
STATE_ORDER = [
    "CurrentlyOccupied",
    "NotOccupied",
    "RecentlyOccupied",
]

# Human-readable model names mapped to their prediction columns.
MODEL_COLUMNS = {
    "Majority baseline": "majority_prediction",
    "Persistence baseline": "persistence_prediction",
    "Random Forest": "random_forest_prediction",
}

REQUIRED_COLUMNS = {
    "window",
    "actual_state",
    *MODEL_COLUMNS.values(),
}


def load_predictions(input_file: Path) -> pd.DataFrame:
    """Load predictions and validate the required columns."""
    if not input_file.is_file():
        raise FileNotFoundError(
            f"Predictions file not found: {input_file}"
        )

    data = pd.read_csv(input_file)

    missing_columns = REQUIRED_COLUMNS - set(data.columns)
    if missing_columns:
        raise ValueError(
            f"Predictions file is missing columns: "
            f"{sorted(missing_columns)}"
        )

    if data.empty:
        raise ValueError("The predictions file contains no rows.")

    if data[list(REQUIRED_COLUMNS)].isna().any().any():
        raise ValueError(
            "Required prediction columns contain missing values. "
            "Check the source predictions before calculating metrics."
        )

    return data


def calculate_class_metrics(data: pd.DataFrame) -> pd.DataFrame:
    """Calculate class-level metrics for every model and test window."""
    results = []

    for window in sorted(data["window"].unique()):
        window_data = data[data["window"] == window]

        print("\n" + "=" * 75)
        print(f"WINDOW: {window}")
        print("=" * 75)
        print(f"Test rows: {len(window_data):,}")

        for model_name, prediction_column in MODEL_COLUMNS.items():
            report = classification_report(
                window_data["actual_state"],
                window_data[prediction_column],
                labels=STATE_ORDER,
                target_names=STATE_ORDER,
                output_dict=True,
                zero_division=0,
            )

            print(f"\n{model_name}")
            print(
                f"{'Class':<22} {'Precision':>10} "
                f"{'Recall':>10} {'F1':>10} {'Support':>10}"
            )

            for state in STATE_ORDER:
                metrics = report[state]
                support = int(metrics["support"])

                print(
                    f"{state:<22} "
                    f"{metrics['precision']:>10.3f} "
                    f"{metrics['recall']:>10.3f} "
                    f"{metrics['f1-score']:>10.3f} "
                    f"{support:>10,}"
                )

                results.append({
                    "window": window,
                    "model": model_name,
                    "class": state,
                    "precision": metrics["precision"],
                    "recall": metrics["recall"],
                    "f1": metrics["f1-score"],
                    "support": support,
                })

    return pd.DataFrame(results)


def main() -> None:
    """Run class-level evaluation and save the results to CSV."""
    print("=" * 75)
    print("ROLLING OCCUPANCY CLASS-LEVEL ANALYSIS")
    print("=" * 75)

    predictions = load_predictions(INPUT_FILE)
    results = calculate_class_metrics(predictions)

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    results.to_csv(OUTPUT_FILE, index=False)

    print(f"\nSaved class-level metrics to:\n{OUTPUT_FILE}")
    print("\nClass-level analysis complete.")


if __name__ == "__main__":
    main()
