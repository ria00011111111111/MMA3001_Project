"""Compare per-class occupancy forecasting performance across rolling windows.

The script analyses predictions generated by the rolling occupancy
evaluation. For each chronological test window and prediction model,
it calculates precision, recall, F1-score, and support for each occupancy
class.

The analysis compares three models:
    - Majority baseline
    - Persistence baseline
    - Random Forest

Metrics are calculated using the fixed occupancy class order defined by
``STATE_ORDER``. This ensures consistent class-level reporting across
models and evaluation windows.

Outputs:
    outputs/occupancy_rolling_evaluation/rolling_class_level_metrics.csv

The output CSV contains one row for each combination of evaluation window,
model, and occupancy class, with the corresponding precision, recall,
F1-score, and support.

Notes:
    This script only analyses previously saved predictions. It does not
    train models, generate new predictions, or modify the original
    prediction file.
"""

from pathlib import Path

import pandas as pd
from sklearn.metrics import classification_report


# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parents[2]

OUTPUT_DIR = PROJECT_ROOT / "outputs" / "occupancy_rolling_evaluation"
INPUT_FILE = OUTPUT_DIR / "rolling_evaluation_predictions.csv"
OUTPUT_FILE = OUTPUT_DIR / "rolling_class_level_metrics.csv"

# Keep this order consistent across evaluation scripts.
STATE_ORDER = [
    "CurrentlyOccupied",
    "NotOccupied",
    "RecentlyOccupied",
]

# Human-readable model names mapped to their prediction columns.
MODEL_COLUMNS = {
    "Majority baseline": "majority_prediction",
    "Persistence baseline": "persistence_prediction",
    "Random Forest": "random_forest_prediction",
}

REQUIRED_COLUMNS = {
    "window",
    "actual_state",
    *MODEL_COLUMNS.values(),
}


def load_predictions(input_file: Path) -> pd.DataFrame:
    """Load and validate the saved rolling evaluation predictions.

    Reads the prediction CSV and checks that all columns required for
    class-level analysis are present. It also verifies that the file
    contains rows and that the required columns do not contain missing
    values.

    Args:
        input_file: Path to the CSV file containing actual occupancy
            states, model predictions, and evaluation window labels.

    Returns:
        A DataFrame containing the validated prediction records.

    Raises:
        FileNotFoundError: If the specified prediction file does not exist.
        ValueError: If required columns are missing, the file contains no
            rows, or any required prediction column contains missing values.

    Note:
        Additional columns in the input file are retained but are not
        required for the class-level calculations.
    """
    if not input_file.is_file():
        raise FileNotFoundError(
            f"Predictions file not found: {input_file}"
        )

    data = pd.read_csv(input_file)

    missing_columns = REQUIRED_COLUMNS - set(data.columns)
    if missing_columns:
        raise ValueError(
            f"Predictions file is missing columns: "
            f"{sorted(missing_columns)}"
        )

    if data.empty:
        raise ValueError("The predictions file contains no rows.")

    if data[list(REQUIRED_COLUMNS)].isna().any().any():
        raise ValueError(
            "Required prediction columns contain missing values. "
            "Check the source predictions before calculating metrics."
        )

    return data


def calculate_class_metrics(data: pd.DataFrame) -> pd.DataFrame:
    """Calculate precision, recall, F1-score, and support per class.

    Processes each evaluation window separately and calculates class-level
    classification metrics for every configured prediction model.

    The scikit-learn ``classification_report`` function is used to calculate
    the metrics. The fixed class labels in ``STATE_ORDER`` ensure that the
    same occupancy classes are reported for every model and window.

    Results are printed to the console and collected into a DataFrame.

    Args:
        data: Validated prediction DataFrame containing the evaluation
            window, actual occupancy state, and prediction columns for
            each configured model.

    Returns:
        A DataFrame containing one row per evaluation window, model, and
        occupancy class. The columns are:

        - ``window``: Chronological evaluation window.
        - ``model``: Name of the prediction model.
        - ``class``: Occupancy state being evaluated.
        - ``precision``: Proportion of predictions for the class that
          were correct.
        - ``recall``: Proportion of actual instances of the class that
          were correctly identified.
        - ``f1``: Harmonic mean of precision and recall.
        - ``support``: Number of actual instances of the class in the
          evaluation window.

    Note:
        ``zero_division=0`` assigns a score of zero when a metric would
        otherwise be undefined because of a zero division.

        All classes in ``STATE_ORDER`` are included in the report, even
        if a class has no actual instances or predictions in a particular
        evaluation window. In such cases, the corresponding support or
        metric values may be zero.
    """
    results = []

    for window in sorted(data["window"].unique()):
        window_data = data[data["window"] == window]

        print("\n" + "=" * 75)
        print(f"WINDOW: {window}")
        print("=" * 75)
        print(f"Test rows: {len(window_data):,}")

        for model_name, prediction_column in MODEL_COLUMNS.items():
            report = classification_report(
                window_data["actual_state"],
                window_data[prediction_column],
                labels=STATE_ORDER,
                target_names=STATE_ORDER,
                output_dict=True,
                zero_division=0,
            )

            print(f"\n{model_name}")
            print(
                f"{'Class':<22} {'Precision':>10} "
                f"{'Recall':>10} {'F1':>10} {'Support':>10}"
            )

            for state in STATE_ORDER:
                metrics = report[state]
                support = int(metrics["support"])

                print(
                    f"{state:<22} "
                    f"{metrics['precision']:>10.3f} "
                    f"{metrics['recall']:>10.3f} "
                    f"{metrics['f1-score']:>10.3f} "
                    f"{support:>10,}"
                )

                results.append({
                    "window": window,
                    "model": model_name,
                    "class": state,
                    "precision": metrics["precision"],
                    "recall": metrics["recall"],
                    "f1": metrics["f1-score"],
                    "support": support,
                })

    return pd.DataFrame(results)


def main() -> None:
    """Run the class-level analysis and save the resulting metrics.

    Loads the saved rolling evaluation predictions, calculates
    class-level metrics for each model and test window, and writes
    the results to the configured output CSV.

    The original prediction file is read but never modified.

    Raises:
        FileNotFoundError: If the rolling evaluation prediction file
            does not exist.
        ValueError: If the prediction file fails validation.
    """
    print("=" * 75)
    print("ROLLING OCCUPANCY CLASS-LEVEL ANALYSIS")
    print("=" * 75)

    predictions = load_predictions(INPUT_FILE)
    results = calculate_class_metrics(predictions)

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    results.to_csv(OUTPUT_FILE, index=False)

    print(f"\nSaved class-level metrics to:\n{OUTPUT_FILE}")
    print("\nClass-level analysis complete.")


if __name__ == "__main__":
    main()